#!/usr/bin/env python3
"""Derive analysis roots for `recomp/symbols.toml` from the disassembly.

Sources of truth, both byte-verified:
  * the ld65 .dbg's `sym` records (labels, with their absolute CPU addresses)
  * the authority JSON's instruction list (so every root is a real instruction
    boundary, never a byte inside a table)

A root is a label that some `jsr`/`jsl` actually targets. Labels that are only
reached by fall-through or that name data are left alone.

Usage:
  gen_symbols.py --dbg <ff6-en.dbg> --authority <authority.json> [--out roots.toml]
                 [--bank C0[,C1...]] [--limit N] [--emit]
"""
import argparse
import collections
import json
import sys


def parse_dbg_labels(path):
    labels = {}      # addr -> [names]
    segs = {}
    with open(path, encoding="utf-8", errors="replace") as handle:
        for raw in handle:
            raw = raw.rstrip("\n")
            if raw.startswith("seg\t"):
                fields = dict(kv.split("=", 1) for kv in raw[4:].split(",") if "=" in kv)
                segs[int(fields["id"], 0)] = (int(fields.get("start", "0"), 0),
                                              fields.get("ooffs") not in (None, ""))
                continue
            if not raw.startswith("sym\t"):
                continue
            fields = dict(kv.split("=", 1) for kv in raw[4:].split(",") if "=" in kv)
            fields = {k: v.strip() for k, v in fields.items()}
            if fields.get("type") != "lab":
                continue
            seg = fields.get("seg")
            if seg is None:
                continue
            seg = int(seg, 0)
            if seg not in segs or not segs[seg][1]:
                continue
            name = fields.get("name", "").strip('"')
            if not name or name.startswith("LOCAL-MACRO_SYMBOL"):
                continue
            addr = int(fields.get("val", "0"), 0)
            if addr < 0x8000:
                continue
            labels.setdefault(addr, []).append(name)
    return labels


def scan_calls(instructions):
    """Collect (target, kind) for every jsr/jsl in the instruction list."""
    calls = collections.Counter()
    for insn in instructions:
        pc = int(insn["pc24"], 0)
        raw = bytes.fromhex(insn["bytes"])
        if not raw:
            continue
        op = raw[0]
        if op == 0x20 and len(raw) >= 3:                       # jsr abs
            calls[((pc & 0xFF0000) | int.from_bytes(raw[1:3], "little"), "jsr")] += 1
        elif op == 0x22 and len(raw) >= 4:                     # jsl long
            calls[(int.from_bytes(raw[1:4], "little"), "jsl")] += 1
    return calls


def main():
    ap = argparse.ArgumentParser()
    # --dbg is optional. With the ld65 .dbg present, roots are the labelled
    # call targets (the disassembly's own entry points). Without it, the bank
    # still comes from the call target's own address, so every
    # instruction-aligned call target is rooted and named from its address.
    # Rebuilding cc65 + the disassembly to recover names costs ~30 min and
    # buys the analysis nothing: cfg names only have to be C identifiers.
    ap.add_argument("--dbg", default="")
    ap.add_argument("--authority", required=True)
    ap.add_argument("--out")
    ap.add_argument("--bank", default="")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--emit", action="store_true")
    ap.add_argument("--stats", action="store_true")
    args = ap.parse_args()

    labels = parse_dbg_labels(args.dbg) if args.dbg else {}
    doc = json.load(open(args.authority))
    code = {int(i["pc24"], 0) for i in doc["instructions"]}
    calls = scan_calls(doc["instructions"])

    banks = {b.upper() for b in args.bank.split(",") if b.strip()}
    roots = []
    for addr, kind in calls:
        if addr not in code:
            continue
        if banks and f"{(addr >> 16) & 0xFF:02X}" not in banks:
            continue
        names = labels.get(addr)
        if labels and not names:
            continue                      # labelled build: only named targets
        roots.append((addr, names[0] if names else f"sub_{addr:06X}", kind,
                      calls[(addr, kind)]))
    roots.sort()
    if args.limit:
        roots = roots[:args.limit]

    if args.stats:
        by_bank = collections.Counter(f"{(a >> 16) & 0xFF:02X}" for a, _, _, _ in roots)
        named = sum(1 for a, _, _, _ in roots if a in labels)
        print(f"labels {len(labels)}  call targets {len(calls)}  rooted {len(roots)}"
              f"  named {named}  address-named {len(roots) - named}")
        print("by bank:", dict(sorted(by_bank.items())))
        for addr, name, kind, n in roots[:10]:
            print(f"  {addr:06X} {name:28s} {kind} x{n}")

    if args.out:
        lines = ["# Generated by tools/gen_symbols.py from the byte-verified",
                 "# disassembly. Roots are labels that jsr/jsl actually target.",
                 ""]
        used = set()
        for addr, name, kind, n in roots:
            # cfg names must be C identifiers: cheap locals (`@0000`) and
            # punctuation get a stable address-based spelling, and repeated
            # names (`End` in two scopes) are disambiguated by address.
            safe = "".join(c if (c.isalnum() or c == "_") else "_" for c in name)
            if not safe or safe[0].isdigit():
                safe = "sub_" + safe
            if safe in used:
                safe = f"{safe}_{addr & 0xFF:04X}_{(addr >> 8) & 0xFF:02X}"
            if safe in used or not safe.isidentifier():
                safe = f"sub_{addr:06X}"
            used.add(safe)
            lines += ["[[func]]",
                      f'name = "{safe}"',
                      f'addr = "{addr & 0xFFFF:04x}"',
                      f"bank = 0x{(addr >> 16) & 0xFF:02X}",
                      f"emit = {'true' if args.emit else 'false'}",
                      f'note = "{kind} target, {n} call site(s)"',
                      ""]
        open(args.out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
        print(f"wrote {len(roots)} roots to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
